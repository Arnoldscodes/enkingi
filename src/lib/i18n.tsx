const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { en, rw };

export function translate(lang: Language, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTIONARIES[lang] as Record<string, string>;
  let text = dict[key] ?? (en as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

interface I18nState {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: TranslationKey | (string & {}), vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nState | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "rw" || saved === "en") setLangState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Language) => {
    setLangState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  const value = useMemo<I18nState>(
    () => ({ lang, setLang, t: (key, vars) => translate(lang, key, vars) }),
    [lang, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useT must be used within LanguageProvider");
  return ctx;
}

/** Translate a category name by its slug; unknown categories keep their stored name. */
export function categoryName(t: I18nState["t"], slug: string, fallback: string): string {
  const key = `cat.${slug}`;
  const text = t(key);
  return text === key ? fallback : text;
}
